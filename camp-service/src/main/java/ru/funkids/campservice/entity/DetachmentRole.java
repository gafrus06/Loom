package ru.funkids.campservice.entity;

/**
 * Роль вожатого внутри конкретного отряда.
 *
 * LEAD      — Главный вожатый. Создаётся автоматически при создании отряда.
 *             Может добавлять и исключать ASSISTANT-ов, изменять этап отряда,
 *             добавлять карточки детей.
 *
 * ASSISTANT — Помощник. Добавляется LEAD-ом или ADMIN-ом лагеря.
 *             Может изменять этап, добавлять детей, но НЕ может исключать
 *             других вожатых (ни LEAD, ни ASSISTANT).
 */
public enum DetachmentRole {
    LEAD,
    ASSISTANT
}